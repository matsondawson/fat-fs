#pragma pack(1)

typedef struct // BPB_FAT16
{
  /*
    BS_DrvNum	36	1	Int 0x13 drive number (e.g. 0x80). This field supports MS-DOS bootstrap and is set to the INT 0x13 drive number of the media (0x00 for floppy disks, 0x80 for hard disks).
    NOTE: This field is actually operating system specific.
  */
  uint8_t BS_DrvNum;
  
  /*
    BS_Reserved1	37	1	Reserved (used by Windows NT). Code that formats FAT volumes should always set this byte to 0.
  */
  uint8_t BS_Reserved1;
  
  /*
    BS_BootSig	38	1	Extended boot signature (0x29). This is a signature byte that indicates that the following three fields in the boot sector are present.
  */
  uint8_t BS_BootSig;
  
  /*
    BS_VolID	39	4	Volume serial number. This field, together with BS_VolLab, supports volume tracking on removable media. These values allow FAT file system drivers to detect that the wrong disk is inserted in a removable drive. This ID is usually generated by simply combining the current date and time into a 32-bit value.
  */
  uint32_t BS_VolID;
  
  /*
    BS_VolLab	43	11	Volume label. This field matches the 11-byte volume label recorded in the root directory.
    NOTE: FAT file system drivers should make sure that they update this field when the volume label file in the root directory has its name changed or created. The setting for this field when there is no volume label is the string “NO NAME    ”.
  */
  uint8_t BS_VolLab[11];
  
  /*
    BS_FilSysType	54	8	One of the strings “FAT12   ”, “FAT16   ”, or “FAT     ”.  NOTE: Many people think that the string in this field has something to do with the determination of what type of FAT—FAT12, FAT16, or FAT32—that the volume has. This is not true. You will note from its name that this field is not actually part of the BPB. This string is informational only and is not used by Microsoft file system drivers to determine FAT typ,e because it is frequently not set correctly or is not present. See the FAT Type Determination section of this document. This string should be set based on the FAT type though, because some non-Microsoft FAT file system drivers do look at it.
  */
  uint8_t BS_FilSysType[8];
} BPB_FAT16;

typedef struct
{
  /*
    BPB_FATSz32	36	4	This field is only defined for FAT32 media and does not exist
            on FAT12 and FAT16 media. This field is the FAT32 32-bit count of sectors occupied
            by ONE FAT. BPB_FATSz16 must be 0.
  */
  uint32_t BPB_FATSz32;
  
  /*
    BPB_ExtFlags	40	2	This field is only defined for FAT32 media and does not exist
    on FAT12 and FAT16 media.
    Bits 0-3	-- Zero-based number of active FAT. Only valid if mirroring is disabled.
    Bits 4-6	-- Reserved.
    Bit      7	-- 0 means the FAT is mirrored at runtime into all FATs.
            -- 1 means only one FAT is active; it is the one referenced in bits 0-3.
    Bits 8-15 	-- Reserved.
  */
  uint16_t BPB_ExtFlags;
  
  /*
    BPB_FSVer	42	2	This field is only defined for FAT32 media and does not exist on
    FAT12 and FAT16 media. High byte is major revision number. Low byte is minor revision
    number. This is the version number of the FAT32 volume. This supports the ability to
    extend the FAT32 media type in the future without worrying about old FAT32 drivers
    mounting the volume. This document defines the version to 0:0.  If this field is non-zero,
    back-level Windows versions will not mount the volume.
    NOTE:  Disk utilities should respect this field and not operate on volumes with a
            higher major or minor version number than that for which they were designed.
            FAT32 file system drivers must check this field and not mount the volume if it
            does not contain a version number that was defined at the time the driver was written.
  */
  uint16_t BPB_FSVer;
  
  
  /*
    BPB_RootClus	44	4	This field is only defined for FAT32 media and does not exist
    on FAT12 and FAT16 media. This is set to the cluster number of the first cluster of the
    root directory, usually 2 but not required to be 2.
    NOTE:  Disk utilities that change the location of the root directory should make every
            effort to place the first cluster of the root directory in the first non-bad cluster
            on the drive (i.e., in cluster 2, unless it’s marked bad). This is specified so that
            disk repair utilities can easily find the root directory if this field accidentally
            gets zeroed.
  */
  uint32_t BPB_RootClus;
  
  /*
    BPB_FSInfo	48	2	This field is only defined for FAT32 media and does not exist on FAT12
    and FAT16 media. Sector number of FSINFO structure in the reserved area of the FAT32 volume.
    Usually 1.
    NOTE: There will be a copy of the FSINFO structure in BackupBoot, but only the copy pointed to
            by this field will be kept up to date (i.e., both the primary and backup boot record will point to the same FSINFO sector).
  */
  uint16_t BPB_FSInfo;
  
  /*
    BPB_BkBootSec	50	2	This field is only defined for FAT32 media and does not exist on FAT12
    and FAT16 media. If non-zero, indicates the sector number in the reserved area of the volume of a copy of the boot record. Usually 6. No value other than 6 is recommended.
  */
  uint16_t BPB_BkBootSec;
  
  /*
    BPB_Reserved	52	12	This field is only defined for FAT32 media and does not exist on FAT12
    and FAT16 media. Reserved for future expansion. Code that formats FAT32 volumes should
    always set all of the bytes of this field to 0.
  */
  uint8_t BPB_Reserved[12];
  
  /*
    BS_DrvNum	64	1	This field has the same definition as it does for FAT12 and FAT16
    media. The only difference for FAT32 media is that the field is at a different offset
    in the boot sector.
  */
  uint8_t BS_DrvNum;
  
  /*
    BS_Reserved1	65	1	This field has the same definition as it does for FAT12 and
    FAT16 meda. The only difference for FAT32 media is that the field is at a different offset in the boot sector.
  */
  uint8_t BS_Reserved1;
  
  /*
    BS_BootSig	66	1	This field has the same definition as it does for FAT12 and FAT16
    media. The only difference for FAT32 media is that the field is at a different offset
    in the boot sector.
  */
  uint8_t BS_BootSig;
  
  /*
    BS_VolID	67	4	This field has the same definition as it does for FAT12 and FAT16
    media. The only difference for FAT32 media is that the field is at a different offset in the boot sector.
  */
  uint32_t BS_VolID;
  
  /*
    BS_VolLab	71	11	This field has the same definition as it does for FAT12 and FAT16
    media. The only difference for FAT32 media is that the field is at a different offset in the boot sector.
  */
  uint8_t BS_VolLab[11];
  
  /*
    BS_FilSysType	82	8	Always set to the string ”FAT32   ”.  Please see the note for
    this field in the FAT12/FAT16 section earlier. This field has nothing to do with FAT type determination.
  */
  uint8_t BS_FilSysType[8];
} BPB_FAT32;

typedef struct // BPB
{
  /** Name / Offset / Bytes / Description **/
  /*
    BS_jmpBoot	0	3	Jump instruction to boot code. This field has two allowed forms:
    jmpBoot[0] = 0xEB, jmpBoot[1] = 0x??, jmpBoot[2] = 0x90
            and
    jmpBoot[0] = 0xE9, jmpBoot[1] = 0x??, jmpBoot[2] = 0x??
  
    0x?? indicates that any 8-bit value is allowed in that byte. What this forms is a
    three-byte Intel x86 unconditional branch (jump) instruction that jumps to the start
    of the operating system bootstrap code. This code typically occupies the rest of
    sector 0 of the volume following the BPB and possibly other sectors. Either of these
    forms is acceptable. JmpBoot[0] = 0xEB is the more frequently used format.
  */
  uint8_t BS_jmpBoot[3];
  
  /*
    BS_OEMName	3	8	“MSWIN4.1” There are many misconceptions about this field.
    It is only a name string. Microsoft operating systems don’t pay any attention to
    this field. Some FAT drivers do. This is the reason that the indicated string,
    “MSWIN4.1”, is the recommended setting, because it is the setting least likely
    to cause compatibility problems. If you want to put something else in here, that
    is your option, but the result may be that some FAT drivers might not recognize
    the volume. Typically this is some indication of what system formatted the volume.
  */
  uint8_t BS_OEMName[8];
  
  /*
    BPB_BytesPerSec	11	2	Count of bytes per sector. This value may take on only the
    following values: 512, 1024, 2048 or 4096. If maximum compatibility with old
    implementations is desired, only the value 512 should be used. There is a lot of
    FAT code in the world that is basically “hard wired” to 512 bytes per sector and
    doesn’t bother to check this field to make sure it is 512. Microsoft operating systems
    will properly support 1024, 2048, and 4096.
    Note: Do not misinterpret these statements about maximum compatibility. If the media
    being recorded has a physical sector size N, you must use N and this must still be less than or equal
    to 4096. Maximum compatibility is achieved by only using media with specific sector sizes.
  */
  uint16_t BPB_BytesPerSec;
  
  /*
    BPB_SecPerClus	13	1	Number of sectors per allocation unit. This value must be a power
    of 2 that is greater than 0. The legal values are 1, 2, 4, 8, 16, 32, 64, and 128. Note however,
    that a value should never be used that results in a “bytes per cluster” value (BPB_BytsPerSec * BPB_SecPerClus)
    greater than 32K (32 * 1024). There is a misconception that values greater than this are OK. Values that cause
    a cluster size greater than 32K bytes do not work properly; do not try to define one. Some versions of some
    systems allow 64K bytes per cluster value. Many application setup programs will not work correctly on such a FAT volume.
  */
  uint8_t BPB_SecPerClus;
  
  /*
    BPB_RsvdSecCnt  14	2	Number of reserved sectors in the Reserved region of the volume
    starting at the first sector of the volume. This field must not be 0. For FAT12 and FAT16 volumes,
    this value should never be anything other than 1.
    For FAT32 volumes, this value is typically 32. There is a lot of FAT code in the world
    “hard wired” to 1 reserved sector for FAT12 and FAT16 volumes and that doesn’t bother to check
    this field to make sure it is 1. Microsoft operating systems will properly support any non-zero
    value in this field.
  */
  uint16_t BPB_RsvdSecCnt;
  
  /*
    BPB_NumFATs	16	1	The count of FAT data structures on the volume. This field should always contain the value 2 for any FAT volume of any type. Although any value greater than or equal to 1 is perfectly valid, many software programs and a few operating systems’ FAT file system drivers may not function properly if the value is something other than 2. All Microsoft file system drivers will support a value other than 2, but it is still highly recommended that no value other than 2 be used in this field.
    The reason the standard value for this field is 2 is to provide redun¬dancy for the FAT data structure so that if a sector goes bad in one of the FATs, that data is not lost because it is duplicated in the other FAT. On non-disk-based media, such as FLASH memory cards, where such redundancy is a useless feature, a value of 1 may be used to save the space that a second copy of the FAT uses, but some FAT file system drivers might not recognize such a volume properly.
  */
  uint8_t BPB_NumFATs;
  
  /*
    BPB_RootEntCnt	17	2	For FAT12 and FAT16 volumes, this field contains the count of 32-byte directory entries in the root directory. For FAT32 volumes, this field must be set to 0. For FAT12 and FAT16 volumes, this value should always specify a count that when multiplied by 32 results in an even multiple of BPB_BytsPerSec. For maximum compatibility, FAT16 volumes should use the value 512.
  */
  uint16_t BPB_RootEntCnt;
  
  /*
    BPB_TotSec16	19	2	This field is the old 16-bit total count of sectors on the volume. This count includes the count of all sectors in all four regions of the volume. This field can be 0; if it is 0, then BPB_TotSec32 must be non-zero. For FAT32 volumes, this field must be 0. For FAT12 and FAT16 volumes, this field contains the sector count, and BPB_TotSec32 is 0 if the total sector count “fits” (is less than 0x10000).
  */
  uint16_t BPB_TotSec16;
  
  /*
    BPB_Media	21	1	0xF8 is the standard value for “fixed” (non-removable) media. For removable media, 0xF0 is frequently used. The legal values for this field are 0xF0, 0xF8, 0xF9, 0xFA, 0xFB, 0xFC, 0xFD, 0xFE, and 0xFF. The only other important point is that whatever value is put in here must also be put in the low byte of the FAT[0] entry. This dates back to the old MS-DOS 1.x media determination noted earlier and is no longer usually used for anything.
  */
  uint8_t BPB_Media;
  
  /*
    BPB_FATSz16	22	2	This field is the FAT12/FAT16 16-bit count of sectors occupied by ONE FAT. On FAT32 volumes this field must be 0, and BPB_FATSz32 contains the FAT size count.
  */
  uint16_t BPB_FATSz16;
  
  /*
    BPB_SecPerTrk	24	2	Sectors per track for interrupt 0x13. This field is only relevant for media that have a geometry (volume is broken down into tracks by multiple heads and cylinders) and are visible on interrupt 0x13. This field contains the “sectors per track” geometry value.
  */
  uint16_t BPB_SecPerTrk;
  
  /*
    BPB_NumHeads	26	2	Number of heads for interrupt 0x13. This field is relevant as discussed earlier for BPB_SecPerTrk. This field contains the one based “count of heads”. For example, on a 1.44 MB 3.5-inch floppy drive this value is 2.
  */
  uint16_t BPB_NumHeads;
  
  /*
    BPB_HiddSec	28	4	Count of hidden sectors preceding the partition that contains this FAT volume. This field is generally only relevant for media visible on interrupt 0x13. This field should always be zero on media that are not partitioned. Exactly what value is appropriate is operating system specific.
  */
  uint32_t BPB_HiddSec;
  
  /*
    BPB_TotSec32 	32	4	This field is the new 32-bit total count of sectors on the volume. This count includes the count of all sectors in all four regions of the volume. This field can be 0; if it is 0, then BPB_TotSec16 must be non-zero. For FAT32 volumes, this field must be non-zero. For FAT12/FAT16 volumes, this field contains the sector count if BPB_TotSec16 is 0 (count is greater than or equal to 0x10000).
  */
  uint32_t BPB_TotSec32;
  
  union
  {
    BPB_FAT16 bpb16; 
    BPB_FAT32 bpb32;
  } bpb;
} BPB_t, *pBPB_t;

